/* Pre-generates a real dotted world map (accurate geo) + office pin coords.
   Output: src/lib/worldmap.generated.ts  (run: node scripts/gen-worldmap.cjs) */
const fs = require("fs");
const path = require("path");
const mod = require("dotted-map");
const DottedMap = mod.default || mod;

const offices = [
  { city: "Amsterdam", role: "HQ", lat: 52.37, lng: 4.9, hq: true },
  { city: "St. Louis", role: "North America", lat: 38.63, lng: -90.2 },
  { city: "Dubai", role: "Middle East", lat: 25.2, lng: 55.27 },
  { city: "Delhi NCR", role: "Engineering", lat: 28.46, lng: 77.03 },
];

// Major trade hubs, for the homepage problem statement (disruption signals)
const hubs = [
  { city: "Rotterdam", lat: 51.92, lng: 4.48 },
  { city: "Shanghai", lat: 31.23, lng: 121.47 },
  { city: "Singapore", lat: 1.29, lng: 103.85 },
  { city: "Los Angeles", lat: 33.74, lng: -118.27 },
  { city: "Santos", lat: -23.96, lng: -46.33 },
  { city: "Suez", lat: 29.97, lng: 32.55 },
  { city: "Houston", lat: 29.76, lng: -95.37 },
  { city: "Busan", lat: 35.1, lng: 129.04 },
  { city: "Mumbai", lat: 18.95, lng: 72.84 },
  { city: "Durban", lat: -29.86, lng: 31.02 },
];

const map = new DottedMap({ height: 48, grid: "diagonal" });

// dots-only SVG (snapshot before adding pins)
const svg = map.getSVG({
  radius: 0.3,
  color: "#8570bf",
  shape: "circle",
  backgroundColor: "transparent",
});

const vb = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
const width = parseFloat(vb[1]);
const height = parseFloat(vb[2]);

const pins = offices.map((o) => {
  const p = map.addPin({ lat: o.lat, lng: o.lng, svgOptions: { radius: 0 } });
  return { city: o.city, role: o.role, hq: !!o.hq, x: p.x, y: p.y };
});

const hubPins = hubs.map((h) => {
  const p = map.addPin({ lat: h.lat, lng: h.lng, svgOptions: { radius: 0 } });
  return { city: h.city, x: p.x, y: p.y };
});

const out = `/* AUTO-GENERATED by scripts/gen-worldmap.cjs. Do not edit by hand. */
export const worldMapWidth = ${width};
export const worldMapHeight = ${height};
export const worldMapSvg = ${JSON.stringify(svg)};
export const worldMapPins: { city: string; role: string; hq: boolean; x: number; y: number }[] = ${JSON.stringify(
  pins
)};
export const worldMapHubs: { city: string; x: number; y: number }[] = ${JSON.stringify(hubPins)};
`;

const dest = path.join(__dirname, "..", "src", "lib", "worldmap.generated.ts");
fs.writeFileSync(dest, out);
console.log("Wrote", dest);
console.log("viewBox", width, "x", height, "· dots svg", svg.length, "chars");
console.log("pins", JSON.stringify(pins, null, 0));
